# One-command onboarding: create .venv, generate .env with a local token, then start.
param([int]$Port = 8766, [switch]$NoStart, [switch]$SkipVenv)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
    $venvPython = Join-Path $root ".venv\Scripts\python.exe"
    if (-not (Test-Path $venvPython)) {
        if ($SkipVenv) { throw ".venv is missing (run without -SkipVenv or create it manually)" }
        Write-Host "创建虚拟环境 .venv ..."
        $launcher = Get-Command py -ErrorAction SilentlyContinue
        if ($launcher) { & py -3 -m venv .venv } else { & python -m venv .venv }
        if ($LASTEXITCODE -ne 0) { throw "python -m venv failed" }
        $venvPython = Join-Path $root ".venv\Scripts\python.exe"
    }
    $envFile = Join-Path $root ".env"
    if (-not (Test-Path $envFile)) {
        $token = [guid]::NewGuid().ToString("N") + [guid]::NewGuid().ToString("N")
        $lines = @(
            "# generated by scripts/quickstart.ps1 - do not commit (gitignored)",
            "TOKENSFREE_LOCAL_TOKEN=$token",
            "TOKENSFREE_ENABLE_REAL=0"
        )
        Set-Content -Path $envFile -Value $lines -Encoding UTF8
        Write-Host "已生成 .env（含本地网关令牌，不入库）"
    } else {
        Write-Host ".env 已存在，保持不变"
    }
    if ($NoStart) {
        Write-Host ""
        Write-Host "准备完成。启动： .\scripts\start.ps1 -Port $Port" -ForegroundColor Green
        return
    }
    & (Join-Path $PSScriptRoot "start.ps1") -Port $Port
} finally {
    Pop-Location
}
